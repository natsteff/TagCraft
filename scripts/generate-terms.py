#!/usr/bin/env python3
"""Generate one informational notice for source readers, in-app display and release packaging."""
from pathlib import Path
import hashlib, json, re, sys
root = Path(__file__).resolve().parents[1]
core = (root / 'Legal/CORE-TERMS.txt').read_text().strip()
notes = (root / 'Legal/TAGCRAFT-NOTES.txt').read_text().strip()
version = re.search(r'^Notice version ([^ •]+)', core, re.M).group(1)
supplement = re.search(r'^Supplement version (\S+)', notes, re.M).group(1)
text = core + '\n\n' + notes + '\n'
license_text = (root / 'LICENSE').read_text()
digest = hashlib.sha256(text.encode()).hexdigest()
source = '// Generated by scripts/generate-terms.py; edit Legal source documents.\nimport Foundation\n\nenum LicenseTerms {\n'
for key, value in [('version',version),('supplementVersion',supplement),('documentHash',digest),('text',text),('licenseText',license_text)]:
    source += '    static let '+key+' = '+json.dumps(value,ensure_ascii=False)+'\n'
source += '}\n'
outputs = {root/'Sources/TagCraft/LicenseTerms.swift': source, root/'USAGE-NOTICE.md': '# TagCraft Music Librarian — License & Usage Notice\n\n'+text+'\nRead the complete [AGPL-3.0 license](LICENSE).\n'}
for path, value in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != value: raise SystemExit('Stale generated terms: '+str(path))
    elif not path.exists() or path.read_text() != value: path.write_text(value)
print('Terms '+version+', supplement '+supplement+', SHA-256 '+digest)
